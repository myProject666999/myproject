CREATE DATABASE IF NOT EXISTS income_expenditure CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE income_expenditure;

DROP TABLE IF EXISTS `record`;
DROP TABLE IF EXISTS `category`;
DROP TABLE IF EXISTS `user_setting`;
DROP TABLE IF EXISTS `holiday`;
DROP TABLE IF EXISTS `user`;

CREATE TABLE `user` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `username` VARCHAR(50) NOT NULL UNIQUE,
    `password` VARCHAR(255) NOT NULL,
    `nickname` VARCHAR(50),
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `category` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `name` VARCHAR(50) NOT NULL,
    `type` TINYINT NOT NULL,
    `icon` VARCHAR(100),
    `sort` INT DEFAULT 0,
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `record` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `user_id` BIGINT NOT NULL,
    `type` TINYINT NOT NULL,
    `category_id` BIGINT NOT NULL,
    `amount` DECIMAL(10,2) NOT NULL,
    `date` DATE NOT NULL,
    `remark` VARCHAR(500),
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_user_date (`user_id`, `date`),
    INDEX idx_user_type (`user_id`, `type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `holiday` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `date` DATE NOT NULL UNIQUE,
    `name` VARCHAR(50) NOT NULL,
    `type` TINYINT DEFAULT 1,
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `user_setting` (
    `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `user_id` BIGINT NOT NULL UNIQUE,
    `color_threshold1` DECIMAL(10,2) DEFAULT 100.00,
    `color_threshold2` DECIMAL(10,2) DEFAULT 300.00,
    `color_threshold3` DECIMAL(10,2) DEFAULT 500.00,
    `color1` VARCHAR(20) DEFAULT '#e8f5e9',
    `color2` VARCHAR(20) DEFAULT '#c8e6c9',
    `color3` VARCHAR(20) DEFAULT '#81c784',
    `color4` VARCHAR(20) DEFAULT '#4caf50',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP,
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

